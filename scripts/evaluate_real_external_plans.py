"""
Evaluation Suite on 12 Real External Floorplans from Public Domain / Historical Archives.
Runs production FloorplanPipeline on actual external plans (HABS, Library of Congress,
historic residential architecture) not generated by our pipeline and outside CubiCasa5K.

Records:
- Wall count, exterior walls, rooms, doors, windows detected.
- Building shell validity rate.
- Detailed qualitative failure analysis (drafting style, line weight, annotations, non-Manhattan geometry).
- Saves side-by-side segmentation visual artifacts to outputs/real_external_results/.
"""

import sys
import json
from pathlib import Path
from PIL import Image, ImageDraw
import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from backend.app.floorplan_engine import FloorplanPipeline
from src.floorplan.dataset import ROOM_CLASSES

def run_real_external_evaluation():
    manifest_path = PROJECT_ROOT / "data" / "real_external_plans" / "real_external_manifest.json"
    if not manifest_path.exists():
        raise FileNotFoundError(f"Manifest not found: {manifest_path}")

    with open(manifest_path, "r") as f:
        manifest = json.load(f)

    out_dir = PROJECT_ROOT / "outputs" / "real_external_results"
    out_dir.mkdir(parents=True, exist_ok=True)

    pipeline = FloorplanPipeline.get_instance()

    print("=" * 90)
    print(f"[REAL EXTERNAL PLANS EVALUATION] Testing on {len(manifest)} External Floorplans")
    print(f"Device: {pipeline.device}")
    print("=" * 90)

    results = []

    for item in manifest:
        plan_id = item["id"]
        filename = item["filename"]
        title = item["title"]
        license_str = item.get("license", "Public Domain")
        img_path = PROJECT_ROOT / "data" / "real_external_plans" / filename

        print(f"\n[*] Processing [{plan_id}]: {filename}...")
        with open(img_path, "rb") as f:
            raw_bytes = f.read()

        try:
            # Run inference with 4-fold TTA
            res = pipeline.process_image(raw_bytes, tta_mode="4_fold", front_only=True)
            layout = res["layout"]
            meta = layout.get("metadata", {})

            num_walls = len(layout.get("walls", []))
            num_ext_walls = sum(1 for w in layout.get("walls", []) if w.get("is_exterior", False))
            num_rooms = len(layout.get("rooms", []))
            num_doors = len(layout.get("doors", []))
            num_windows = len(layout.get("windows", []))
            is_shell_valid = meta.get("is_building_shell_valid", False)
            shell_status = meta.get("shell_status", "UNKNOWN")
            perim_m = meta.get("building_perimeter_m", 0.0)
            area_m2 = meta.get("total_surface_m2", 0.0)

            # Diagnose failure mode / challenge
            diagnostics = []
            if not is_shell_valid:
                if num_rooms == 0:
                    diagnostics.append("Failure: Zero rooms partitioned (raster room mask lacked closed wall boundaries).")
                elif num_walls < 4:
                    diagnostics.append("Failure: Fragmented outer perimeter (fewer than 4 walls detected).")
                else:
                    diagnostics.append(f"Failure: Non-watertight building envelope ({shell_status}).")
            else:
                diagnostics.append("Success: Watertight building envelope and rectilinear room partition established.")

            if num_doors == 0:
                diagnostics.append("Challenge: No standard door swing arcs present in drawing drafting style.")
            if num_windows == 0:
                diagnostics.append("Challenge: Window openings flush with walls or absent in schematic.")

            # Save visual inspection artifact
            orig_img = Image.open(img_path).convert("RGB")
            w_orig, h_orig = orig_img.size
            scale = min(512 / w_orig, 512 / h_orig)
            nw, nh = int(w_orig * scale), int(h_orig * scale)
            preview = orig_img.resize((nw, nh), Image.Resampling.BILINEAR)

            vis_canvas = Image.new("RGB", (1024, 512), (245, 245, 245))
            vis_canvas.paste(preview, ((512 - nw) // 2, (512 - nh) // 2))

            # Draw vector overlay on right half
            draw = ImageDraw.Draw(vis_canvas)
            offset_x = 512

            # Draw walls
            scale_m = meta.get("scale_meters_per_pixel", meta.get("scale_m_per_px", 0.03))
            for w in layout.get("walls", []):
                pts_m = w.get("polygon_meters", [])
                if len(pts_m) >= 3:
                    pts_px = [(offset_x + int(round(pt[0] / scale_m)), int(round(pt[1] / scale_m))) for pt in pts_m]
                    color = (220, 20, 60) if w.get("is_exterior") else (70, 70, 70)
                    draw.polygon(pts_px, fill=color, outline=(0, 0, 0))

            # Draw rooms
            for r in layout.get("rooms", []):
                pts_m = r.get("polygon_meters", [])
                if len(pts_m) >= 3:
                    pts_px = [(offset_x + int(round(pt[0] / scale_m)), int(round(pt[1] / scale_m))) for pt in pts_m]
                    draw.line(pts_px + [pts_px[0]], fill=(0, 150, 255), width=2)

            vis_out = out_dir / f"{plan_id}_vector_overlay.png"
            vis_canvas.save(vis_out)

            record = {
                "id": plan_id,
                "filename": filename,
                "title": title,
                "license": license_str,
                "num_walls": num_walls,
                "num_exterior_walls": num_ext_walls,
                "num_rooms": num_rooms,
                "num_doors": num_doors,
                "num_windows": num_windows,
                "is_building_shell_valid": is_shell_valid,
                "shell_status": shell_status,
                "building_perimeter_m": perim_m,
                "total_surface_m2": area_m2,
                "status": "PASS" if is_shell_valid else "FAIL_GEOMETRY",
                "diagnostics": diagnostics,
                "overlay_artifact": str(vis_out.name)
            }
            results.append(record)
            print(f"  [+] Shell: {shell_status} | Walls: {num_walls} | Rooms: {num_rooms} | Doors: {num_doors} | Area: {area_m2:.1f} m²")

        except Exception as e:
            print(f"  [!] Inference failed: {e}")
            results.append({
                "id": plan_id,
                "filename": filename,
                "title": title,
                "status": "CRASH",
                "error": str(e)
            })

    # Summary
    n_total = len(results)
    n_valid_shell = sum(1 for r in results if r.get("is_building_shell_valid", False))
    n_rooms_detected = sum(1 for r in results if r.get("num_rooms", 0) > 0)

    summary = {
        "dataset": "Real External Floorplans (Wikimedia Commons / HABS / Library of Congress)",
        "total_plans_tested": n_total,
        "watertight_shell_success_rate": f"{(n_valid_shell / max(n_total, 1)) * 100:.1f}%",
        "room_detection_success_rate": f"{(n_rooms_detected / max(n_total, 1)) * 100:.1f}%",
        "plan_evaluations": results
    }

    report_file = out_dir / "real_external_evaluation_report.json"
    with open(report_file, "w") as f:
        json.dump(summary, f, indent=2)

    print("\n" + "=" * 90)
    print("REAL EXTERNAL PLANS EVALUATION SUMMARY")
    print("=" * 90)
    print(f"Total External Plans:        {n_total}")
    print(f"Watertight Shell Valid:      {n_valid_shell}/{n_total} ({summary['watertight_shell_success_rate']})")
    print(f"Room Partitioning Detected:  {n_rooms_detected}/{n_total} ({summary['room_detection_success_rate']})")
    print(f"Report saved to:             {report_file}")
    print("=" * 90)

if __name__ == "__main__":
    run_real_external_evaluation()
